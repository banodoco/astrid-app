#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const producer = process.argv[2] ?? process.env.ASTRID_RUNTIME_CHECKOUT;
if (!producer) throw new Error('Usage: node scripts/sync-runtime-client.mjs <astrid-runtime checkout>');
const checkout = path.resolve(producer);
const commit = execFileSync('git', ['-C', checkout, 'rev-parse', 'HEAD'], { stdio: ['ignore', 'pipe', 'pipe'] }).toString('utf8').trim();
const lockPath = path.join(root, 'runtime.lock.json');
const previous = readFileSync(lockPath, 'utf8');
const lock = JSON.parse(previous);
const provisional = process.argv.includes('--provisional');
const responses = 'src/integrations/runtime/fixtures/responses/';
const legacyConflict = `${responses}publish_conflict_409.json`;
const manifest = JSON.parse(readFileSync(path.join(checkout, lock.manifest), 'utf8'));
const committed = (file) => {
  try { execFileSync('git', ['-C', checkout, 'cat-file', '-e', `${commit}:${file}`], { stdio: 'pipe' }); return true; }
  catch { return false; }
};
const commitTypes = 'packages/typescript/src/timeline-commit-types.ts';
if (provisional ? committed(commitTypes) : Object.hasOwn(manifest.artifacts, commitTypes)) {
  lock.files['src/integrations/runtime/timeline-commit-types.ts'] ??= { from: commitTypes };
}
if (lock.files[legacyConflict] &&
    ['commit_conflict_409', 'retired_route_410'].every((name) =>
      provisional
        ? committed(`conformance/responses/${name}.json`)
        : Object.hasOwn(manifest.artifacts, `conformance/responses/${name}.json`))) {
  // D39 records conflicts on /commit; retired publishers now return 410.
  const entry = lock.files[legacyConflict];
  delete lock.files[legacyConflict];
  for (const name of ['commit_conflict_409', 'retired_route_410']) {
    lock.files[`${responses}${name}.json`] = { ...entry, from: `conformance/responses/${name}.json` };
  }
}
lock.source_commit = commit;
if (provisional) {
  // Focused tests only: some WIP producers have not regenerated artifacts.json.
  // Verify every byte against Git instead; never manufacture a published manifest.
  const files = Object.entries(lock.files).map(([target, entry]) => {
    const bytes = execFileSync('git', ['-C', checkout, 'show', `${commit}:${entry.from}`], { maxBuffer: 20 * 1024 * 1024 });
    if (!bytes.equals(readFileSync(path.join(checkout, entry.from)))) throw new Error(`Producer working bytes differ: ${entry.from}`);
    return { target, bytes, entry };
  });
  for (const { target, bytes, entry } of files) {
    writeFileSync(path.join(root, target), bytes);
    entry.sha256 = `sha256:${createHash('sha256').update(bytes).digest('hex')}`;
  }
  lock.provisional = { reason: 'WIP producer artifact manifest is stale; exact Git bytes for focused tests only. Rebind at I-AP-07.' };
  lock.producer_version = `provisional:${commit}`;
  writeFileSync(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
  console.log(`PROVISIONAL focused-test contract from ${commit}; producer-manifest qualification pending I-AP-07`);
  process.exit(0);
}
delete lock.provisional;
writeFileSync(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
try {
  // The existing updater verifies the committed producer manifest before copying generated bytes.
  execFileSync(process.execPath, [path.join(root, 'scripts/vendor-lock.mjs'), 'update', lockPath, '--producer', checkout], { stdio: 'inherit' });
} catch (error) {
  writeFileSync(lockPath, previous);
  throw error;
}
