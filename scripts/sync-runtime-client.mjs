#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const producer = process.argv[2] ?? process.env.ASTRID_RUNTIME_CHECKOUT;
if (!producer) throw new Error('Usage: node scripts/sync-runtime-client.mjs <astrid-runtime checkout>');
const checkout = path.resolve(producer);
const commit = execFileSync('git', ['-C', checkout, 'rev-parse', 'HEAD'], { stdio: ['ignore', 'pipe', 'pipe'] }).toString('utf8').trim();
const lockPath = path.join(root, 'runtime.lock.json');
const previous = readFileSync(lockPath, 'utf8');
const lock = JSON.parse(previous);
const responses = 'src/integrations/runtime/fixtures/responses/';
const legacyConflict = `${responses}publish_conflict_409.json`;
if (lock.files[legacyConflict]) {
  // D39 records conflicts on /commit; retired publishers now return 410.
  const entry = lock.files[legacyConflict];
  delete lock.files[legacyConflict];
  for (const name of ['commit_conflict_409', 'retired_route_410']) {
    lock.files[`${responses}${name}.json`] = { ...entry, from: `conformance/responses/${name}.json` };
  }
}
lock.source_commit = commit;
writeFileSync(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
try {
  // The existing updater verifies the committed producer manifest before copying generated bytes.
  execFileSync(process.execPath, [path.join(root, 'scripts/vendor-lock.mjs'), 'update', lockPath, '--producer', checkout], { stdio: 'inherit' });
} catch (error) {
  writeFileSync(lockPath, previous);
  throw error;
}
